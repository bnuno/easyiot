    inline void sampleStops(const PaletteStop *stops, uint8_t count, float t, uint8_t &outR, uint8_t &outG, uint8_t &outB)
    {
        if (count == 0)
        {
            outR = outG = outB = 0;
            return;
        }
        t -= floorf(t);
        if (t < 0.f) t += 1.f;
        const float pos = t * 255.f;
        if (pos <= stops[0].pos || count == 1)
        {
            outR = stops[0].r; outG = stops[0].g; outB = stops[0].b;
            return;
        }
        if (pos >= stops[count - 1].pos)
        {
            outR = stops[count - 1].r; outG = stops[count - 1].g; outB = stops[count - 1].b;
            return;
        }
        for (uint8_t i = 0; i < count - 1; i++)
        {
            const PaletteStop &a = stops[i];
            const PaletteStop &b = stops[i + 1];
            if (pos >= a.pos && pos <= b.pos)
            {
                const float span = (b.pos > a.pos) ? (float)(b.pos - a.pos) : 1.f;
                const float f = (pos - a.pos) / span;
                outR = (uint8_t)(a.r + (b.r - a.r) * f);
                outG = (uint8_t)(a.g + (b.g - a.g) * f);
                outB = (uint8_t)(a.b + (b.b - a.b) * f);
                return;
            }
        }
    }
